// Generates supabase/seed.sql from the recipe library and demo coupons in the code.
// Usage: npm run seed:sql
import { build } from "esbuild";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
const dir = mkdtempSync(join(tmpdir(), "mpp-seed-"));
const out = join(dir, "entry.mjs");
await build({
  stdin: { contents: 'export { RECIPES } from "@/lib/recipes/library"; export { demoCoupons } from "@/lib/demo/coupons";', resolveDir: root, loader: "ts" },
  bundle: true, format: "esm", platform: "node", outfile: out, alias: { "@": root }, logLevel: "error"
});
const { RECIPES, demoCoupons } = await import(pathToFileURL(out).href);

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

let sql = "-- Seed data for MyPantryPal: recipe library and DEMONSTRATION coupons (fictional stores, is_demo = true).\n-- Generated by scripts/generate-seed.mjs. Created by Daria Pugacheva.\n\n";
for (const r of RECIPES) {
  sql += `insert into public.recipes (id,name,description,cuisine,preparation_time,difficulty,servings,calories,protein,carbohydrates,fat,ingredients,instructions,tags,allergens,palette) values (${[
    q(r.id), q(r.name), q(r.description), q(r.cuisine), r.preparation_time, q(r.difficulty), r.servings, r.calories, r.protein, r.carbohydrates, r.fat,
    json(r.ingredients), json(r.instructions), arr(r.tags), arr(r.allergens), arr(r.palette)
  ].join(",")}) on conflict (id) do update set name = excluded.name, ingredients = excluded.ingredients, instructions = excluded.instructions;\n`;
}
sql += "\n";
for (const c of demoCoupons()) {
  sql += `insert into public.coupons (id,store_name,product_name,discount,expiration_date,description,conditions,is_demo) values (${[q(c.id), q(c.store_name), q(c.product_name), q(c.discount), q(c.expiration_date), q(c.description), q(c.conditions), "true"].join(",")}) on conflict (id) do update set expiration_date = excluded.expiration_date;\n`;
}
writeFileSync(join(root, "supabase", "seed.sql"), sql);
console.log(`Wrote supabase/seed.sql (${RECIPES.length} recipes, ${demoCoupons().length} demo coupons)`);
